"use client";
import { useEffect, useState } from "react";
import { useFeedbackMessage, useActionFeedback } from "../ActionFeedback";
import { Modal } from "./InvestorUI";
import { deviceRequest, type DeviceSignIn, type DeviceSignInStatus } from "@/lib/reid/device";

export function ReidDeviceSignIn({ authorization, csrfToken, next, onClose }: { authorization: DeviceSignIn; csrfToken: string; next: string; onClose: () => void }) {
  const [status, setStatus] = useState("pending");
  const [error, setError] = useState("");
  const { available: feedbackAvailable } = useActionFeedback();
  useFeedbackMessage(error && status === "pending" ? `${error} Checking again shortly.` : status === "denied" ? "You declined this sign-in. Close this window to try again." : status === "expired" ? "This sign-in code expired. Connect with reID again." : "");
  useEffect(() => {
    let active = true; let timer: ReturnType<typeof setTimeout>;
    const expiry = setTimeout(() => { if (active) { setStatus("expired"); clearTimeout(timer); } }, Math.max(0, Date.parse(authorization.expiresAt) - Date.now()));
    async function poll() {
      if (!active || Date.parse(authorization.expiresAt) <= Date.now()) return;
      let delay = authorization.interval;
      try {
        const result = await deviceRequest<DeviceSignInStatus>("POST", "auth/reid/device/poll", csrfToken);
        if (!active) return;
        if (result.status === "approved") { clearTimeout(expiry); setStatus("approved"); window.location.assign(next); return; }
        if (result.status !== "pending") { clearTimeout(expiry); setStatus(result.status); return; }
        if (!Number.isSafeInteger(result.interval) || result.interval < 5 || result.interval > 300) throw new Error("Sign-in status could not be verified.");
        delay = Math.max(delay, result.interval); setError("");
      } catch (problem) { if (!active) return; setError(problem instanceof Error ? problem.message : "Status is unavailable. Keep this sign-in open."); delay = Math.max(delay, 15); }
      if (active) timer = setTimeout(() => void poll(), delay * 1000);
    }
    timer = setTimeout(() => void poll(), authorization.interval * 1000);
    return () => { active = false; clearTimeout(timer); clearTimeout(expiry); };
  }, [authorization, csrfToken, next]);
  function close() { void deviceRequest("DELETE", "auth/reid/device", csrfToken).catch(() => undefined); onClose(); }
  return <Modal title="Connect with the reID mobile app" onClose={close}><p>Open the scanner inside the reID mobile app and scan this code, then review and approve access. This page will sign in automatically.</p>{status === "pending" ? <div className="iv-reid-mobile-qr">
    {/* eslint-disable-next-line @next/next/no-img-element -- QR is generated by our API, never a remote image */}
    <img src={authorization.qrDataUrl} width={240} height={240} alt="Scan with the reID app scanner to sign in" />
    <p>Or enter this code in reID: <strong>{authorization.userCode}</strong></p>
  </div> : null}<p role="status" aria-live="polite">{status === "pending" ? "Waiting for your approval in the reID mobile app…" : status === "approved" ? "Connected. Opening your investor dashboard…" : status === "denied" ? "You declined this sign-in. Close this window to try again." : "This sign-in code expired. Close this window and continue with reID again."}</p>{error && status === "pending" ? <p className="iv-form-error" role={feedbackAvailable ? undefined : "alert"}>{error} Checking again shortly.</p> : null}<p className="iv-muted">Only scan the code shown on your own sign-in page. Approve access only when you started this request.</p></Modal>;
}
